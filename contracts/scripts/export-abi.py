"""Exports ABIs after `forge build`: full ABIs to contracts/abi, trimmed ABIs to the TS SDK."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sdk = {
    "AgentAccount": ["requestPayment", "setPolicy", "setPayee", "setDomain", "setPaused", "revoke", "withdraw", "liquid",
                     "parkedValue", "totalValue", "totalDebt", "policy", "remainingToday", "spentToday", "paused", "revoked",
                     "owner", "agentSigner", "allowedPayee", "isPayeeAllowed", "positions", "PaymentRequested", "PolicySet"],
    "SettlementRouter": ["Settled", "buffers"],
    "AgentAccountFactory": ["createAccount", "accountsOf", "AccountCreated", "isAccount", "predictAddress"],
    "UnsleptBuffer": ["deposit", "withdraw", "redeem", "requestWithdraw", "claimWithdraw", "processQueue", "totalAssets",
                      "available", "utilizationBps", "maxWithdraw", "convertToAssets", "balanceOf", "debtOf", "ticket",
                      "ticketCount", "outstandingPrincipal", "queueThresholdBps", "Advanced", "Repaid", "WithdrawRequested",
                      "WithdrawFunded", "WithdrawClaimed", "Deposit", "Withdraw", "asset", "decimals", "previewRedeem", "maxDeposit"],
}
full = ["AgentAccount", "SettlementRouter", "AgentAccountFactory", "UnsleptBuffer", "Allocator", "FeeModule",
        "UnsleptStaking", "ERC4626Adapter"]
os.makedirs(f"{root}/abi", exist_ok=True)
for c in full:
    abi = json.load(open(f"{root}/out/{c}.sol/{c}.json"))["abi"]
    json.dump(abi, open(f"{root}/abi/{c}.json", "w"), indent=1)
src = "// Generated by contracts/scripts/export-abi.py. Do not edit by hand.\n"
for c, names in sdk.items():
    abi = json.load(open(f"{root}/out/{c}.sol/{c}.json"))["abi"]
    keep = [x for x in abi if x.get("name") in names or x["type"] == "error"]
    src += f"export const {c[0].lower() + c[1:]}Abi = {json.dumps(keep, separators=(',', ':'))} as const;\n\n"
open(f"{root}/../packages/sdk-ts/src/abi.ts", "w").write(src)
print("abi exported")
